-- ============================================================
--  Миграция 005 — клуб по умолчанию (переходный период)
--
--  Пока старые ссылки/QR первого клуба ещё без кода клуба, вход без кода
--  должен вести именно в него. Раньше это работало, только пока клуб в
--  базе один; помечаем первый клуб явным флагом, чтобы фолбэк держался и
--  когда клубов станет несколько (после первых подключений).
--
--  Выполнить в Supabase SQL Editor. Идемпотентно.
-- ============================================================

alter table clubs add column if not exists is_default boolean not null default false;

-- Первый (существующий) клуб — дефолтный.
update clubs set is_default = true  where code = 'club01';
-- На всякий случай снимаем флаг с любых других (дефолт должен быть один).
update clubs set is_default = false where code <> 'club01';

notify pgrst, 'reload schema';
